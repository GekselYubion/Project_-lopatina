# Дан список a размера n. Вывести его элементы в следующем порядке: \(A_{1}\), \(A_{n}\), \(A_{2}\), \(A_{n-1}\), \(A_{3}\), \(A_{n-2}\), ....
a = list(map(int, input("Введите элементы через пробел: ").split()))
n = len(a)

for i in range(n // 2):
    print(a[i], a[-1-i], end=" ")
if n % 2 !=0:
    print(a[n//2])
