# Условие третьей задачи: «Дан список размера N. Осуществить циклический сдвиг элементов списка
# влево на одну позицию (при этом \(a_{N}\) перейдет в
#  \(a_{N-1}\), \(a_{N-1}\) — в \(a_{N-2}\), ..., \(a_{1}\) — в \(a_{N}\))».

a = [10, 20, 30, 40, 50]
n = len(a)

first = a[0]

for i in range(n - 1):
    a[i] =a[i + 1]

a[-1] = first

print(a)  # Выведет: [20, 30, 40, 50, 10]
