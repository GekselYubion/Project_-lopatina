# Даны три целых числа: A, B, C. Проверить истинность высказывания: «Ровно одно из чисел A, B, C положительное».

while True:
    try:
        a= int(input("введи число А "))
        b = int(input("введи В число "))
        c = int(input("введи С число ")) 
        break
    except ValueError:
        print("можно вводить только числа ")

rez = (a>0)+(b>0)+(c>0)
if rez == 1:
    print("«Ровно одно из чисел A, B, C положительное».")
else:
    print("нет положительных чисел или ")
